function compare(unit, ...rows) {
  return { kind: 'compare', unit, items: rows.map(([label, value, amount]) => ({ label, value, amount })) };
}
function metric(value, label) {
  return { kind: 'metric', items: [{ label, value }] };
}
function check(...rows) {
  return { kind: 'checklist', items: rows.map(([label, value]) => ({ label, value })) };
}
function card(id, category, title, body, takeaway, visual, secondTitle) {
  const highlight = visual.kind === 'metric' ? visual.items[0] : null;
  return { id, category, title, body, takeaway, visual,
    ...(highlight ? { metric: highlight.value, metricLabel: highlight.label } : {}),
    facts: [body, ...visual.items.map(({ label, value }) => label + ' · ' + value + (visual.unit ? ' (' + visual.unit + ')' : ''))],
    alternative: { title: secondTitle, cta: takeaway } };
}

