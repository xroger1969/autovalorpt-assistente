export const ADVICE_DAILY_COUNT = DAILY.length;
export const ADVICE_EXTRA_COUNT = EXTRA.length;

export function adviceFor(date, extra = false, indexOverride) {
  if (typeof date !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(date)) throw new RangeError('editorial_date_invalid');
  const time = Date.parse(date + 'T00:00:00Z');
  if (!Number.isFinite(time) || new Date(time).toISOString().slice(0, 10) !== date) throw new RangeError('editorial_date_invalid');
  const day = (time - Date.parse(ADVICE_START_DATE + 'T00:00:00Z')) / DAY;
  if (day < 0) throw new RangeError('editorial_date_before_start');
  const index = indexOverride ?? day;
  if (!Number.isSafeInteger(index) || index < 0) throw new RangeError('editorial_index_invalid');
  const bank = extra ? EXTRA : DAILY;
  // Every caller receives fresh text/visual structures, including nested arrays.
  const selected = bank[index % bank.length];
  // The 26 November artwork already has a public immutable URL.
  if (selected.id === updatedCostComparison.id && date > ADVICE_START_DATE) return structuredClone(updatedCostComparison);
  return structuredClone(selected);
}
